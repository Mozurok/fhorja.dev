#!/usr/bin/env python3
"""Regenerate evals/skill-description-baseline.json.

The FIX side of check_description_reference_preservation, the same split
scripts/reconcile-counts.sh has with the count-marker check: one place asserts, another
place updates, and the update lands as a reviewable diff rather than as a silent pass.

Run this when a description changes ON PURPOSE. The diff it produces is the whole point:
the gate cannot stop someone from regenerating the baseline, only from doing it without
anyone seeing. That limit is stated here rather than left for a reader to discover, and
the scenario that will carry it for a human audience is not written yet.

    python3 evals/scripts/build-description-baseline.py            # write
    python3 evals/scripts/build-description-baseline.py --check    # exit 1 if stale

This imports the parser from structural-evals.py instead of carrying its own. That is the
constraint the slice was built under: the descriptions are YAML block scalars, two parsers
written for the single-line shape were discarded on this surface, and a builder with its
own copy would reintroduce exactly the divergence the shared helper removes.
"""

import os
import sys
import json
import importlib.util

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, "..", ".."))
BASELINE = os.path.join(REPO, "evals", "skill-description-baseline.json")


def _load_structural_evals():
    """Import structural-evals.py by path; its hyphen makes it unimportable by name."""
    path = os.path.join(HERE, "structural-evals.py")
    spec = importlib.util.spec_from_file_location("structural_evals", path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def build():
    """Compute the baseline from the real corpus.

    Deliberately takes NO root parameter. It carried one briefly, and that was a defect:
    the corpus was parameterized while the write target stayed the fixed BASELINE path, so
    building from a 3-skill fixture would have overwritten the 98-skill baseline the gate
    depends on. Nothing called it that way, which is exactly why it was worth removing
    rather than guarding. If a future caller genuinely needs to build from another corpus,
    the output path becomes a parameter in the same change, never one without the other.
    """
    se = _load_structural_evals()
    descriptions, files = se.skill_descriptions()
    if len(descriptions) != len(files):
        raise SystemExit(f"parsed {len(descriptions)} descriptions from {len(files)} files; refusing to write a partial baseline")
    references = se.description_references(descriptions)
    return {
        "_comment": (
            "Generated by evals/scripts/build-description-baseline.py. Do not hand-edit. "
            "Consumed by check_description_reference_preservation in structural-evals.py "
            "(scenario 133, ADR-0135 item 2). Regenerate deliberately when a description "
            "changes on purpose; the diff is the review surface."
        ),
        "skills": len(references),
        "references": references,
    }


def main(argv):
    check_only = "--check" in argv
    fresh = build()
    if check_only:
        if not os.path.exists(BASELINE):
            print(f"[FAIL] {os.path.relpath(BASELINE, REPO)} does not exist")
            return 1
        with open(BASELINE, "r", encoding="utf-8") as f:
            current = json.load(f)
        if current.get("references") != fresh["references"]:
            print(f"[FAIL] {os.path.relpath(BASELINE, REPO)} is stale; run without --check to update")
            return 1
        print(f"[OK] baseline matches the corpus ({fresh['skills']} skills)")
        return 0
    with open(BASELINE, "w", encoding="utf-8") as f:
        json.dump(fresh, f, indent=2, sort_keys=True, ensure_ascii=False)
        f.write("\n")
    total = sum(len(v) for v in fresh["references"].values())
    print(f"[OK] wrote {os.path.relpath(BASELINE, REPO)}: {fresh['skills']} skills, {total} cross-references")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
